from acb.benchmarks.scarfbench import ScarfBench, _ensure_validation_harness


def test_compatibility_makefile_runs_benchmark_script_without_url_override(tmp_path):
    target = tmp_path / "business_domain" / "standalone" / "quarkus"
    target.mkdir(parents=True)
    (target / "test.sh").write_text("#!/bin/bash\n"
                                    "test -z \"${BASE_URL:-}\" || exit 3\n"
                                    "echo 'Health check: http://localhost:8080/standalone'\n")
    _ensure_validation_harness(tmp_path, layer="business_domain", app="standalone",
                               framework="quarkus")

    fake_bin = tmp_path / "bin"
    fake_bin.mkdir()
    docker = fake_bin / "docker"
    docker.write_text(
        "#!/bin/sh\n"
        "case \"$1\" in\n"
        "  build) echo sha256:fixture > \"$3\"; exit 0 ;;\n"
        "  rm) exit 0 ;;\n"
        "  run) echo fake-container; exit 0 ;;\n"
        "  exec)\n"
        "    if [ \"${FAKE_FAIL:-0}\" = 1 ]; then exit 1; fi\n"
        "    shift 2\n"
        "    if [ \"$1\" = bash ]; then bash test.sh; else exit 0; fi ;;\n"
        "  logs) exit 0 ;;\n"
        "esac\n"
    )
    docker.chmod(0o755)
    env = {**os.environ, "PATH": f"{fake_bin}:{os.environ['PATH']}"}
    env.pop("BASE_URL", None)
    result = subprocess.run(["make", "test"], cwd=target, env=env,
                            capture_output=True, text=True, check=False)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "Health check: http://localhost:8080/standalone" in result.stdout
    assert "Application started and ready." in result.stdout
    assert "===== 1 passed =====" in result.stdout
    assert "BASE_URL=" not in (target / "Makefile").read_text()

    failed = subprocess.run(["make", "test"], cwd=target,
                            env={**env, "FAKE_FAIL": "1"}, capture_output=True,
                            text=True, check=False)
    assert failed.returncode != 0
    assert "Application container exited" in failed.stdout
    assert "Application started and ready." not in failed.stdout
    assert "===== 1 passed =====" not in failed.stdout


def test_compatibility_makefile_preserves_upstream_and_replaces_old_acb(tmp_path):
    target = tmp_path / "business_domain" / "cart" / "quarkus"
    target.mkdir(parents=True)
    (target / "test.sh").write_text("#!/bin/sh\nexit 0\n")
    makefile = target / "Makefile"
    makefile.write_text("test:\n\t@echo upstream\n")
    _ensure_validation_harness(tmp_path, layer="business_domain", app="cart",
                               framework="quarkus")
    assert makefile.read_text() == "test:\n\t@echo upstream\n"

    makefile.write_text("IMAGE_NAME ?= scarfbench-cart-quarkus:latest\n"
                        "test:\n\t@docker exec -e BASE_URL=http://localhost:8080/api/cart/health\n")
    _ensure_validation_harness(tmp_path, layer="business_domain", app="cart",
                               framework="quarkus")
    assert "docker exec $(CONTAINER_NAME) bash /app/test.sh" in makefile.read_text()
    assert "BASE_URL=" not in makefile.read_text()

    # Upgrade the most recent ACB-generated recipe too, without replacing an
    # upstream Makefile. Both versions previously used the shared image tag.
    makefile.write_text("# Generated by ACB for ScarfBench v0.1.2's missing Makefile.\n"
                        "IMAGE_NAME ?= scarfbench-cart-quarkus:latest\n")
    _ensure_validation_harness(tmp_path, layer="business_domain", app="cart", framework="quarkus")
    assert "--iidfile" in makefile.read_text()


def test_interleaved_validations_run_their_own_built_image(tmp_path):
    """A builds, B replaces any shared tag, then A starts its container."""
    template = tmp_path / "benchmark/business_domain/cart/quarkus"
    template.mkdir(parents=True)
    (template / "test.sh").write_text("exit 0\n")
    _ensure_validation_harness(tmp_path / "benchmark", layer="business_domain", app="cart", framework="quarkus")
    for name in ("a", "b"):
        directory = tmp_path / name
        directory.mkdir()
        shutil.copy(template / "Makefile", directory / "Makefile")
        (directory / "project.txt").write_text(name)

    fake_bin = tmp_path / "bin"
    fake_bin.mkdir()
    docker = fake_bin / "docker"
    docker.write_text(f"#!{sys.executable}\n" + '''
import hashlib, os, sys, time
from pathlib import Path
root = Path(os.environ['FAKE_ENGINE'])
cwd = Path.cwd()
args = sys.argv[1:]
def wait(path):
    deadline = time.monotonic() + 10
    while not path.exists():
        if time.monotonic() >= deadline:
            raise RuntimeError('interleaving barrier timed out')
        time.sleep(.01)
if args[0] == 'build':
    name = (cwd / 'project.txt').read_text()
    if name == 'b': wait(root / 'a-built')
    identity = 'sha256:' + hashlib.sha256(name.encode()).hexdigest()
    if '--iidfile' in args:
        (cwd / args[args.index('--iidfile') + 1]).write_text(identity)
    if '-t' in args:
        (root / 'shared-tag').write_text(identity)
    (root / (name + '-built')).touch()
    if name == 'a': wait(root / 'b-built')
elif args[0] == 'run':
    reference = args[-1]
    identity = reference if reference.startswith('sha256:') else (root / 'shared-tag').read_text()
    (cwd / 'ran-image.txt').write_text(identity)
elif args[0] == 'exec':
    import hashlib
    expected = 'sha256:' + hashlib.sha256((cwd / 'project.txt').read_bytes()).hexdigest()
    sys.exit(0 if (cwd / 'ran-image.txt').read_text() == expected else 1)
''')
    docker.chmod(0o755)
    env = {**os.environ, "PATH": f"{fake_bin}:{os.environ['PATH']}", "FAKE_ENGINE": str(tmp_path)}

    def validate(name):
        return subprocess.run(["make", "test"], cwd=tmp_path / name, env=env,
                              text=True, capture_output=True, timeout=20)

    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(validate, ("a", "b")))
    assert all(result.returncode == 0 for result in results), [r.stdout + r.stderr for r in results]
    assert (tmp_path / "a/ran-image.txt").read_text() != (tmp_path / "b/ran-image.txt").read_text()


def test_make_failure_overrides_success_metadata(tmp_path):
    instance_id = "business_domain/cart/jakarta-to-quarkus"
    output_dir = tmp_path / "goose"
    instance_dir = output_dir / "instances" / "business_domain__cart__jakarta-to-quarkus"
    instance_dir.mkdir(parents=True)
    (instance_dir / "prediction.json").write_text(json.dumps({
        "instance_id": instance_id,
        "model_name_or_path": "test-model",
    }))

    run_dir = (
        output_dir / "scarfbench-eval" /
        "acb__business_domain__cart__jakarta__quarkus" / "run_1"
    )
    validation_dir = run_dir / "validation"
    validation_dir.mkdir(parents=True)
    (validation_dir / "run.log").write_text(
        "status=1; if [ $status -eq 0 ]; then echo '===== 1 passed ====='; fi\n"
        "Error: can only create exec sessions on running containers\n"
        "make: *** [test] Error 1\n"
    )
    (run_dir / "metadata.json").write_text(json.dumps({
        "layer": "business_domain",
        "app": "cart",
        "target_framework": "quarkus",
        "compile_ok": "TRUE",
        "deploy_ok": "TRUE",
        "tests_passed": 1,
        "num_smoke_tests": 1,
    }))

    benchmark_dir = tmp_path / "benchmark"
    target_dir = benchmark_dir / "business_domain" / "cart" / "quarkus"
    target_dir.mkdir(parents=True)
    (target_dir / "test.sh").write_text("#!/bin/sh\nexit 0\n")
    bench = ScarfBench({"benchmark_cache_dir": str(benchmark_dir)})
    with patch("acb.benchmarks.scarfbench.shutil.which", return_value="/mock/scarf"), \
         patch("acb.benchmarks.scarfbench.container_env", return_value={}), \
         patch("acb.benchmarks.scarfbench.subprocess.run", return_value=SimpleNamespace(returncode=0)):
        assert bench.evaluate(None, "test-run", output_dir, instance_id=instance_id) == {
            instance_id: False
        }
