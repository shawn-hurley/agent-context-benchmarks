def test_compatibility_makefile_runs_benchmark_script_without_url_override(tmp_path):
    target = tmp_path / "business_domain" / "standalone" / "quarkus"
    target.mkdir(parents=True)
    (target / "test.sh").write_text("#!/bin/bash\n"
                                    "test -z \"${BASE_URL:-}\" || exit 3\n"
                                    'BASE_URL="${BASE_URL:-http://localhost:8080/standalone}"\n'
                                    'echo "Health check: ${BASE_URL}"\n')
    _ensure_validation_harness(tmp_path, layer="business_domain", app="standalone",
                               framework="quarkus")

    fake_bin = tmp_path / "bin"
    fake_bin.mkdir()
    docker = fake_bin / "docker"
    docker.write_text(
        "#!/bin/sh\n"
        "case \"$1\" in\n"
        "  build) echo sha256:fixture > \"$3\"; exit 0 ;;\n"
        "  rm) exit 0 ;;\n"
        "  run) printf '%s\\n' \"$@\" | grep -qx 'QUARKUS_HTTP_PORT=8080' || exit 4; "
        "echo fake-container; exit 0 ;;\n"
        "  exec)\n"
        "    if [ \"${FAKE_FAIL:-0}\" = 1 ]; then exit 1; fi\n"
        "    shift 2\n"
        "    if [ \"$1\" = bash ]; then bash test.sh; else exit 0; fi ;;\n"
        "  logs) exit 0 ;;\n"
        "esac\n"
    )
    docker.chmod(0o755)
    env = {**os.environ, "PATH": f"{fake_bin}:{os.environ['PATH']}"}
    env.pop("BASE_URL", None)
    result = subprocess.run(["make", "test"], cwd=target, env=env,
                            capture_output=True, text=True, check=False)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "Health check: http://localhost:8080/standalone" in result.stdout
    assert "Application started and ready." in result.stdout
    assert "===== 1 passed =====" in result.stdout
    assert "BASE_URL=" not in (target / "Makefile").read_text()
    assert "-e QUARKUS_HTTP_PORT=8080" in (target / "Makefile").read_text()

    failed = subprocess.run(["make", "test"], cwd=target,
                            env={**env, "FAKE_FAIL": "1"}, capture_output=True,
                            text=True, check=False)
    assert failed.returncode != 0
    assert "Application container exited" in failed.stdout
    assert "Application started and ready." not in failed.stdout
    assert "===== 1 passed =====" not in failed.stdout


def test_compatibility_makefile_preserves_upstream_and_replaces_old_acb(tmp_path):
    target = tmp_path / "business_domain" / "cart" / "quarkus"
    target.mkdir(parents=True)
    (target / "test.sh").write_text(
        '#!/bin/sh\nBASE_URL="${BASE_URL:-http://localhost:8080/cart}"\nexit 0\n'
    )
    makefile = target / "Makefile"
    makefile.write_text("test:\n\t@echo upstream\n")
    _ensure_validation_harness(tmp_path, layer="business_domain", app="cart",
                               framework="quarkus")
    assert makefile.read_text() == "test:\n\t@echo upstream\n"

    makefile.write_text("IMAGE_NAME ?= scarfbench-cart-quarkus:latest\n"
                        "test:\n\t@docker exec -e BASE_URL=http://localhost:8080/api/cart/health\n")
    _ensure_validation_harness(tmp_path, layer="business_domain", app="cart",
                               framework="quarkus")
    assert "docker exec $(CONTAINER_NAME) bash /app/test.sh" in makefile.read_text()
    assert "BASE_URL=" not in makefile.read_text()
    assert "-e QUARKUS_HTTP_PORT=8080" in makefile.read_text()

    # Upgrade both earlier generated recipes without replacing upstream files.
    makefile.write_text("# Generated by ACB for ScarfBench v0.1.2's missing Makefile.\n"
                        "IMAGE_NAME ?= scarfbench-cart-quarkus:latest\n")
    _ensure_validation_harness(tmp_path, layer="business_domain", app="cart", framework="quarkus")
    assert "--iidfile" in makefile.read_text()

    makefile.write_text("# Generated by ACB for ScarfBench v0.1.2's missing Makefile.\n"
                        "IMAGE_ID_FILE := .acb-validation-image-id\n"
                        "build:\n\tdocker build --iidfile $(IMAGE_ID_FILE) .\n")
    _ensure_validation_harness(tmp_path, layer="business_domain", app="cart", framework="quarkus")
    assert "-e QUARKUS_HTTP_PORT=8080" in makefile.read_text()

    (target / "test.sh").write_text(
        '#!/bin/sh\nBASE_URL="${BASE_URL:-http://localhost:9080/cart}"\nexit 0\n'
    )
    _ensure_validation_harness(tmp_path, layer="business_domain", app="cart", framework="quarkus")
    assert "-e QUARKUS_HTTP_PORT=9080" in makefile.read_text()
    assert "-e QUARKUS_HTTP_PORT=8080" not in makefile.read_text()


@pytest.mark.parametrize(("base_url", "expected_port"), [
    ("http://localhost:8080/counter", 8080),
    ("http://127.0.0.1:9080/", 9080),
    ("http://localhost:8082/order", 8082),
    ("http://example.com:8080/counter", None),
    ("https://localhost:8080/counter", None),
    ("http://localhost:99999/counter", None),
])
def test_target_http_port_uses_only_literal_local_http_url(tmp_path, base_url, expected_port):
    script = tmp_path / "test.sh"
    script.write_text(f'BASE_URL="${{BASE_URL:-{base_url}}}"\n')
    assert _target_http_port(script) == expected_port


